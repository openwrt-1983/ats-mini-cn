#!/usr/bin/env python3
"""Generate FontCN16.h / FontCN24.h for the ATS-Mini CN firmware.

Renders the UI glyph subset of Noto Sans CJK SC as 1-bit bitmaps in the
LovyanGFX GFXfont bit-stream format (raw row-major MSB-first bits, run-rendered
by GFXfont::drawChar) with TRUE per-glyph bounding boxes and a shared baseline,
so mixed Latin/CJK text aligns correctly and Light-weight strokes stay thin.

Glyph set: printable ASCII plus every non-ASCII character found in the
firmware sources (union of the sets embedded in the previous headers).

Usage (from the repo root):
    python3 tools/gen_font.py \
        --font tools/NotoSansCJKsc-Light.otf \
        --output ats-mini

Requires: freetype-py  (pip install freetype-py)
"""

import argparse
import glob
import os
import re
import sys

import freetype

HEADER_TEMPLATE = """\
#ifndef {guard}
#define {guard}

#include <lgfx/v1/lgfx_fonts.hpp>

// Generated by tools/gen_font.py - do not edit by hand.
// Glyph set: ASCII + every non-ASCII character used by the firmware sources.
// Source: {font_name}, FreeType {render}, true bounding boxes, shared baseline.
static const uint8_t {prefix}_bitmaps[] PROGMEM = {{
{bitmaps}
}};

static const lgfx::GFXglyph {prefix}_glyphs[] PROGMEM = {{
{glyphs}
}};

static const lgfx::EncodeRange {prefix}_ranges[] PROGMEM = {{
{ranges}
}};

// {glyph_count} glyphs, {bitmap_bytes} bitmap bytes, baseline {baseline}, yAdvance {yadv}
static const lgfx::GFXfont {prefix_obj} = {{
  (uint8_t*){prefix}_bitmaps,
  (lgfx::GFXglyph*){prefix}_glyphs,
  0x{first:04X}, 0x{last:04X},
  {yadv},
  {range_count}, (lgfx::EncodeRange*){prefix}_ranges
}};

#endif
"""


def collect_glyph_set(source_dir):
    """ASCII printables + every non-ASCII codepoint in the firmware sources."""
    codes = set(range(0x20, 0x7F))
    patterns = ("*.cpp", "*.h", "*.ino")
    for pattern in patterns:
        for path in glob.glob(os.path.join(source_dir, pattern)):
            with open(path, encoding="utf-8", errors="ignore") as fh:
                for ch in fh.read():
                    if ord(ch) > 0x7E:
                        codes.add(ord(ch))
    return sorted(codes)


def render_glyph(face, code):
    """Render one codepoint, return (grid, xAdvance, xOffset, top) or None."""
    face.load_char(chr(code), freetype.FT_LOAD_NO_HINTING)
    g = face.glyph
    g.render(freetype.FT_RENDER_MODE_MONO)
    bmp = g.bitmap
    advance = (g.advance.x + 32) >> 6  # round(advance_px)
    if bmp.width == 0 or bmp.rows == 0:
        return ([], advance, g.bitmap_left, g.bitmap_top)
    rows = []
    buf = bmp.buffer
    pitch = abs(bmp.pitch)
    span = (bmp.width + 7) // 8
    for y in range(bmp.rows):
        base = y * pitch
        row = []
        for x in range(bmp.width):
            byte = buf[base + (x >> 3)]
            row.append((byte >> (7 - (x & 7))) & 1)
        rows.append(row)
    return (rows, advance, g.bitmap_left, g.bitmap_top)


def build_font(face, codes, pixel_size, baseline_hint):
    face.set_pixel_sizes(0, pixel_size)
    entries = []
    for code in codes:
        r = render_glyph(face, code)
        if r is None:
            print(f"  warning: no glyph for U+{code:04X}", file=sys.stderr)
            continue
        rows, adv, left, top = r
        entries.append({"code": code, "rows": rows, "adv": adv,
                        "left": left, "top": top})

    # Font-level vertical metrics from real ink extents.
    ascent = 0
    descent = 0
    for e in entries:
        if not e["rows"]:
            continue
        ascent = max(ascent, e["top"])
        bottom = len(e["rows"]) - e["top"]  # rows below baseline
        descent = max(descent, bottom)

    baseline = min(ascent, baseline_hint) if baseline_hint else ascent
    yadv = pixel_size  # keep the layout line pitch the firmware was designed for

    # Pack bitmaps: raw row-major MSB-first bits, continuous across rows,
    # padded to a byte boundary per glyph (LovyanGFX GFXfont bit stream).
    bitmap = []
    glyphs_tbl = []
    for e in entries:
        rows, adv, left, top = e["rows"], e["adv"], e["left"], e["top"]
        w = len(rows[0]) if rows else 0
        h = len(rows)
        if w == 0 or h == 0:
            w = h = 0
        offset = len(bitmap)
        bits = []
        for row in rows:
            bits.extend(row)
        if bits:
            # GFXfont::drawChar advances by runs and discovers a run's end only
            # when it meets an opposite bit, so the last run needs a terminator
            # (otherwise the decoder runs into the next glyph).
            bits.append(0 if bits[-1] else 1)
        while len(bits) % 8:
            bits.append(0)
        for i in range(0, len(bits), 8):
            byte = 0
            for b in bits[i:i + 8]:
                byte = (byte << 1) | b
            bitmap.append(byte)
        if not bits:  # empty glyph still occupies one byte
            bitmap.append(0)
        glyphs_tbl.append((e["code"], offset, w, h, adv, left, -top))

    # Build encode ranges over consecutive codepoint runs.
    ranges = []
    run_start = None
    prev_code = None
    for idx, entry in enumerate(glyphs_tbl):
        code = entry[0]
        if run_start is None:
            run_start, prev_code = idx, code
        elif code == prev_code + 1:
            prev_code = code
        else:
            ranges.append((glyphs_tbl[run_start][0], prev_code, run_start))
            run_start, prev_code = idx, code
    if run_start is not None:
        ranges.append((glyphs_tbl[run_start][0], prev_code, run_start))

    return {"bitmap": bitmap, "glyphs": glyphs_tbl, "ranges": ranges,
            "baseline": baseline, "yadv": yadv,
            "grids": {e["code"]: e["rows"] for e in entries if e["rows"]}}


def decode_glyph(bitmap, glyph):
    """Decode one GFXglyph exactly like GFXfont::drawChar does (verification)."""
    off, w, h, _adv, _xoff, _yoff = glyph
    pos, mask, bitlen = off, 0x80, 0
    btmp = bitmap[pos] if pos < len(bitmap) else 0
    if btmp & mask:
        btmp = (~btmp) & 0xFFFFFFFF
    grid = [[0] * w for _ in range(h)]
    neg = lambda v: v & 0x80000000
    row = 0
    guard = 0
    while row < h:
        j, remain = 0, w
        while remain:
            guard += 1
            if guard > 4 * w * h + 64:
                raise SystemExit(f"decode did not terminate for w={w} h={h}")
            if bitlen == 0:
                btmp = (~btmp) & 0xFFFFFFFF
                while True:
                    bitlen += 1
                    if bitlen > w * h + 8:
                        raise SystemExit("run longer than the glyph: "
                                         "missing terminator bit")
                    mask >>= 1
                    if mask == 0:
                        pos += 1
                        nb = bitmap[pos] if pos < len(bitmap) else 0
                        btmp = (nb ^ 0xFFFFFFFF) if neg(btmp) else nb
                        mask = 0x80
                    if not (btmp & mask):
                        break
            take = min(bitlen, remain)
            remain -= take
            bitlen -= take
            start, j = j, j + take
            if not neg(btmp):
                for xx in range(start, min(j, w)):
                    grid[row][xx] = 1
        row += 1
    return grid


def verify(font_data):
    """Every glyph must decode back to the grid it was built from."""
    for code, offset, w, h, adv, left, yoff in font_data["glyphs"]:
        if w == 0 or h == 0:
            continue
        got = decode_glyph(font_data["bitmap"], (offset, w, h, adv, left, yoff))
        want = font_data["grids"][code]
        if got != want:
            raise SystemExit(f"verify failed for U+{code:04X}")
    print(f"  verified {len(font_data['glyphs'])} glyphs round-trip")


def emit(font_data, font_name, pixel_size, guard, prefix, out_path):
    bitmap_lines = []
    bm = font_data["bitmap"]
    for i in range(0, len(bm), 16):
        chunk = bm[i:i + 16]
        bitmap_lines.append("  " + ",".join(f"0x{b:02X}" for b in chunk) + ",")

    glyph_lines = []
    for code, offset, w, h, adv, left, yoff in font_data["glyphs"]:
        glyph_lines.append(
            f"  {{ {offset:>6}, {w:>3}, {h:>3}, {adv:>3}, {left:>4}, {yoff:>5} }},"
            f" // U+{code:04X} '{chr(code)}'")

    range_lines = []
    for start, end, base in font_data["ranges"]:
        range_lines.append(f"  {{ 0x{start:04X}, 0x{end:04X}, {base} }},")

    content = HEADER_TEMPLATE.format(
        guard=guard, font_name=font_name, render="mono unhinted",
        prefix=prefix, prefix_obj=f"font_cn_{pixel_size}",
        bitmaps="\n".join(bitmap_lines),
        glyphs="\n".join(glyph_lines),
        ranges="\n".join(range_lines),
        glyph_count=len(font_data["glyphs"]),
        bitmap_bytes=len(bm),
        range_count=len(font_data["ranges"]),
        baseline=font_data["baseline"],
        yadv=font_data["yadv"],
        first=font_data["glyphs"][0][0],
        last=font_data["glyphs"][-1][0],
    )
    with open(out_path, "w") as fh:
        fh.write(content)
    print(f"wrote {out_path}: {len(font_data['glyphs'])} glyphs, "
          f"{len(bm)} bitmap bytes, baseline {font_data['baseline']}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=os.path.join(os.path.dirname(__file__),
                                                   "NotoSansCJKsc-Light.otf"))
    ap.add_argument("--source-dir", default=None,
                    help="firmware dir to scan for used characters "
                         "(default: <repo>/ats-mini)")
    ap.add_argument("--output", default=None,
                    help="output dir for the headers (default: same as source)")
    ap.add_argument("--sizes", type=int, nargs="+", default=[16, 24])
    args = ap.parse_args()

    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source_dir = args.source_dir or os.path.join(repo, "ats-mini")
    out_dir = args.output or source_dir

    codes = collect_glyph_set(source_dir)
    print(f"glyph set: {len(codes)} codepoints")

    face = freetype.Face(args.font)
    for size in args.sizes:
        # Keep CJK ink inside the classic cell: top <= size*14/16.
        hint = round(size * 14 / 16)
        data = build_font(face, codes, size, hint)
        verify(data)
        emit(data, os.path.basename(args.font), size,
             f"FONT_CN_{size}_H", f"font_cn_{size}",
             os.path.join(out_dir, f"FontCN{size}.h"))


if __name__ == "__main__":
    main()
